// Build tool: generate the 30 levels of Where Is My Coin and write them to
// game/src/levels.js. Every level is verified here, in Node, with the same
// solver the game ships: exactly one solution, connected regions, one solution
// coin per region. Run: node tools/generate-levels.mjs
// The output is deterministic: the same seeds always write the same file.
//
// Difficulty ramp: a pool of single-solution boards is built per board size,
// sorted by the solver's search-tree size (nodes — a stand-in for how hard
// the level is), and levels take boards in that order, so the ramp is
// monotonic: levels 1-5 on 8x8, levels 6-30 on 10x10, easiest first.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { BIG_SIZE, LEVELS_TOTAL, SMALL_LEVELS, SMALL_SIZE } from '../game/src/config.js';
import {
  countSolutions,
  generateLevel,
  regionsAreConnected,
} from '../game/src/puzzle.js';

/** Build `wanted` single-solution boards of size n, drawing fresh seeds until the pool fills. */
function buildPool(n, wanted, seedBase) {
  const pool = [];
  let seed = seedBase;
  let draws = 0;
  while (pool.length < wanted) {
    draws += 1;
    const level = generateLevel(n, seed);
    seed += 7919;
    if (level === null) continue;
    // Independent re-verification, from the written data only.
    if (countSolutions(n, level.regions, 2).count !== 1) throw new Error(`pool ${n}: solver disagrees`);
    if (!regionsAreConnected(n, level.regions)) throw new Error(`pool ${n}: disconnected region`);
    for (let row = 0; row < n; row += 1) {
      if (level.regions[row * n + level.solution[row]] !== row) throw new Error(`pool ${n}: bad solution coin`);
    }
    pool.push(level);
  }
  pool.sort((a, b) => a.nodes - b.nodes);
  return { pool, draws };
}

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, '..', 'game', 'src', 'levels.js');

const t0 = Date.now();
const small = buildPool(SMALL_SIZE, SMALL_LEVELS, 0x51c01);
const big = buildPool(BIG_SIZE, LEVELS_TOTAL - SMALL_LEVELS, 0x9e3779b9);
const chosen = [...small.pool, ...big.pool];

const levels = [];
const report = [];
for (let number = 1; number <= LEVELS_TOTAL; number += 1) {
  const level = chosen[number - 1];
  const minSize = Math.min(...level.sizes);
  const maxSize = Math.max(...level.sizes);
  levels.push({ n: level.n, regions: level.regions, solution: level.solution });
  report.push(
    `level ${String(number).padStart(2, '0')} ${level.n}x${level.n} seed=${level.seed} nodes=${level.nodes} ` +
      `regionSizes=${minSize}..${maxSize}`,
  );
}

const header = `// Where Is My Coin — the 30 levels, generated by tools/generate-levels.mjs
// with the seeded generator in puzzle.js and verified there: every level has
// exactly one solution, connected regions, one solution coin per region.
// Do not edit by hand; regenerate with: node tools/generate-levels.mjs
`;
const body = `export const LEVELS = [\n${levels.map((l) => `  ${JSON.stringify(l)},`).join('\n')}\n];\n`;
writeFileSync(outPath, header + body);
console.log(report.join('\n'));
console.log(`pools: 8x8 ${small.pool.length} boards in ${small.draws} draws, 10x10 ${big.pool.length} boards in ${big.draws} draws`);
console.log(`wrote ${outPath} (${levels.length} levels) in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
